import { DEFAULT_LOCALE, type Locale } from "@/i18n/locales";

/**
 * Словари интерфейса.
 *
 * ### Почему ключ — сам русский текст
 *
 * `t("Добавить в корзину")`, а не `t("cart.add")`.
 *
 * Русский — исходный язык проекта и останется основным (ТЗ §13.3), значит
 * ключ и так пришлось бы держать рядом с русским текстом. Придуманные
 * ключи в такой ситуации дают три беды: восемьсот имён надо изобрести,
 * в коде вместо текста остаются `cart.add.button.label`, а непереведённая
 * строка показывается человеку как сам ключ.
 *
 * С русским ключом всё три исчезают: код читается как раньше, а отсутствие
 * перевода **само собой** даёт русский текст — ровно тот откат, который
 * выбран и на бэкенде.
 *
 * Плата: правка русской формулировки обнуляет её перевод. Для проекта,
 * где переводы появятся один раз и большими партиями, это дешевле, чем
 * изобретать и потом сопровождать восемьсот ключей.
 *
 * ### Подстановки
 *
 * `t("Показано {count}", { count: 12 })`. Фигурные скобки, а не `${}`:
 * шаблонная строка вычислилась бы до вызова `t`, и в словарь пришёл бы
 * ключ с уже подставленным числом — то есть свой ключ на каждое значение.
 */
export type Dictionary = Record<string, string>;

/**
 * Переводы по языкам. Русского здесь нет и не будет: его «перевод» —
 * это сам ключ.
 *
 * Заводить язык — добавить сюда словарь и вписать его в
 * `AVAILABLE_LOCALES`. Пока переводов нет ни одного, и это рабочее
 * состояние: витрина полностью на русском, механика на месте.
 */
export const DICTIONARIES: Partial<Record<Locale, Dictionary>> = {
  // ky: kyDictionary,
  // en: enDictionary,
};

export type TranslateValues = Record<string, string | number>;

/**
 * Переводит строку и подставляет значения.
 *
 * Неизвестный ключ возвращается как есть — это и есть откат на русский,
 * а не «поломка». Поэтому же нет ни предупреждений в консоль, ни пометок
 * вида `[missing]`: непереведённая строка на витрине должна выглядеть
 * обычным текстом.
 */
export function translate(
  locale: Locale,
  source: string,
  values?: TranslateValues,
): string {
  const template =
    locale === DEFAULT_LOCALE ? source : (DICTIONARIES[locale]?.[source] ?? source);

  if (!values) return template;

  return template.replace(/\{(\w+)\}/g, (whole, key: string) =>
    key in values ? String(values[key]) : whole,
  );
}
