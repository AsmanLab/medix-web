/**
 * Тексты, пришедшие из API.
 *
 * Их переводит сервер: в ответе есть `name`/`description` на языке запроса
 * (с откатом на русский) и устаревшие `name_ru`/`description_ru` строго
 * на своём языке. Витрина должна брать первое.
 *
 * ### Почему не просто `product.name`
 *
 * Витрина может уехать раньше бэкенда. В схеме `name` обязательное —
 * у него есть значение по умолчанию, — поэтому TypeScript считает его
 * строкой, а старый сервер его просто не пришлёт. Тогда на карточках
 * окажется пустота вместо названий: не ошибка, а молча пустой каталог.
 *
 * Проверка типом, а не `?? ""`: пустая строка от нового сервера значит
 * «названия действительно нет», и её подменять на `name_ru` не нужно.
 * Это то же правило, по которому сделан счётчик товаров в категории.
 */
export function contentText(
  translated: string | undefined | null,
  legacy: string | undefined | null,
): string {
  return typeof translated === "string" ? translated : (legacy ?? "");
}
