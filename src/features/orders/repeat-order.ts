/**
 * «Повторить заказ» — сборка позиций прошлого заказа обратно в корзину.
 *
 * Не создаёт заказ напрямую, хотя ТЗ §3.9 формулирует пункт как «`POST /orders`
 * с теми же позициями». Между заказами цены меняются, товар снимают с продажи,
 * а часть позиций уходит в КП вместо прямого заказа — решает это сервер при
 * оформлении корзины. Через корзину клиент видит актуальные цены и состав
 * до того, как что-то отправит, и правит их обычными средствами.
 */

import type { OrderLineItem } from "@/api/orders";

export type CartAddition = {
  productId: string;
  qty: number;
  /** id товаров-опций: корзина принимает комплектацию именно так. */
  optionIds: string[];
  /** Название базовой позиции — нужно, чтобы назвать её в сообщении об ошибке. */
  name: string;
};

/**
 * Разворачивает плоский список строк заказа в набор добавлений в корзину.
 *
 * Опции лежат отдельными строками и указывают на базовую через
 * `parent_line_id`; корзина же принимает товар вместе с опциями одним
 * запросом. Строки-сироты (родителя нет в заказе) пропускаются: без базового
 * товара опция бессмысленна, а как самостоятельный товар она бы добавилась
 * в корзину отдельной позицией — этого клиент не заказывал.
 */
export function orderToCartAdditions(items: OrderLineItem[]): CartAddition[] {
  const bases = items.filter((i) => !i.option_type);

  return bases.map((base) => ({
    productId: base.product_id,
    // Количество опций считается на единицу базового товара и едет за ним,
    // поэтому берём количество только базовой строки.
    qty: base.qty,
    optionIds: items
      .filter((i) => i.parent_line_id === base.id)
      .map((i) => i.product_id),
    name: base.name,
  }));
}
