import { describe, expect, test } from "vitest";
import { parseDescription } from "@/features/catalog/product-description";

describe("parseDescription", () => {
  test("пустое описание не даёт блоков", () => {
    expect(parseDescription("")).toEqual([]);
    expect(parseDescription(null)).toEqual([]);
    expect(parseDescription("   \n  ")).toEqual([]);
  });

  test("абзацы разделяются пустой строкой", () => {
    const blocks = parseDescription("Первый абзац.\n\nВторой абзац.");
    expect(blocks).toEqual([
      { kind: "paragraph", text: "Первый абзац." },
      { kind: "paragraph", text: "Второй абзац." },
    ]);
  });

  test("соседние строки одного абзаца склеиваются", () => {
    const blocks = parseDescription("Звуковое оповещение о начале.\nБыстрое начало анализа.");
    expect(blocks).toEqual([
      {
        kind: "paragraph",
        text: "Звуковое оповещение о начале. Быстрое начало анализа.",
      },
    ]);
  });

  test("«Ключ: значение» становится характеристикой", () => {
    const blocks = parseDescription(
      "Производительность: 120 анализов в час\nПамять: 1000 результатов",
    );
    expect(blocks).toEqual([
      {
        kind: "specs",
        rows: [
          { label: "Производительность", value: "120 анализов в час" },
          { label: "Память", value: "1000 результатов" },
        ],
      },
    ]);
  });

  test("одинокая длинная строка с двоеточием остаётся абзацем", () => {
    // Лимит на длину значения действует только для строки без соседей —
    // рядом нет других характеристик, значит это, вероятнее всего, обычное
    // вступление вида «Важно: …», а не таблица из одной строки.
    const long =
      "Важно: " + "этот прибор предназначен для лабораторий ".repeat(6);
    const blocks = parseDescription(long);
    expect(blocks).toHaveLength(1);
    expect(blocks[0].kind).toBe("paragraph");
  });

  test("маркированный список собирается в один блок", () => {
    const blocks = parseDescription("• фотометрия\n• турбидиметрия\n• кинетика");
    expect(blocks).toEqual([
      { kind: "list", items: ["фотометрия", "турбидиметрия", "кинетика"] },
    ]);
  });

  test("короткая строка перед характеристиками — заголовок раздела", () => {
    const blocks = parseDescription("Образцы\nТипы проб: сыворотка, плазма");
    expect(blocks).toEqual([
      { kind: "heading", text: "Образцы" },
      { kind: "specs", rows: [{ label: "Типы проб", value: "сыворотка, плазма" }] },
    ]);
  });

  test("одинокая короткая строка остаётся абзацем", () => {
    // Заголовок без содержимого — это просто короткое предложение.
    expect(parseDescription("Комплектация")).toEqual([
      { kind: "paragraph", text: "Комплектация" },
    ]);
  });

  test("реальное описание разбирается по типам блоков", () => {
    const blocks = parseDescription(
      [
        "CL-50 Plus портативный анализатор мочи.",
        "",
        "Производительность: 120 анализов в час",
        "",
        "Методы расчета и измерений:",
        "• фотометрия",
        "• кинетика",
        "",
        "Память: 1000 результатов",
      ].join("\n"),
    );

    expect(blocks.map((b) => b.kind)).toEqual([
      "paragraph",
      "specs",
      "heading",
      "list",
      "specs",
    ]);
    // «Методы расчета и измерений:» вводит список ниже — это подзаголовок,
    // а не абзац, и двоеточие в заголовке не остаётся.
    expect(blocks[2]).toEqual({ kind: "heading", text: "Методы расчета и измерений" });
    // «Память: …» стоит уже после списка — заголовок его не поглощает,
    // это отдельная таблица из одной строки.
    expect(blocks[4]).toEqual({
      kind: "specs",
      rows: [{ label: "Память", value: "1000 результатов" }],
    });
  });

  // ── Реальные случаи с прода (Medix, 07.09.2026) ──────────────────────────
  // Все строки ниже — дословные фрагменты живых описаний товаров, на которых
  // старый разбор (лимит 160 знаков на значение, 40 — на название, разбор по
  // кускам между пустыми строками) давал обычный абзац вместо таблицы.

  test("длинное значение рядом с характеристикой становится строкой таблицы", () => {
    const long =
      "Режимы расчета: Конечная точка, Абсорбция, бихроматическое считывание, " +
      "линейная регрессия, многоточечный режим (количество стандартов до 8ми), " +
      "многоточечная нелинейная регрессия, кинетика, фактор";
    expect(long.length).toBeGreaterThan(160);

    const blocks = parseDescription(
      `Принцип измерения: Абсорбция, одновременное считывание в 8-ми лунках\n${long}`,
    );
    expect(blocks).toEqual([
      {
        kind: "specs",
        rows: [
          {
            label: "Принцип измерения",
            value: "Абсорбция, одновременное считывание в 8-ми лунках",
          },
          {
            label: "Режимы расчета",
            value: long.slice(long.indexOf(":") + 1).trim(),
          },
        ],
      },
    ]);
  });

  test("двоеточие внутри значения не ломает разбор характеристики", () => {
    const blocks = parseDescription(
      "Производительность: 60 тестов в час\n" +
        "Определяемые параметры: 25 параметров + 4 исследовательских: WBC, RBC, HGB",
    );
    expect(blocks).toEqual([
      {
        kind: "specs",
        rows: [
          { label: "Производительность", value: "60 тестов в час" },
          {
            label: "Определяемые параметры",
            value: "25 параметров + 4 исследовательских: WBC, RBC, HGB",
          },
        ],
      },
    ]);
  });

  test("название характеристики длиной до 64 знаков распознаётся", () => {
    const label = "Встроенная проточная термостатируемая кювета";
    expect(label.length).toBeGreaterThan(40);
    expect(label.length).toBeLessThanOrEqual(64);

    const blocks = parseDescription(`${label}: из кварцевого стекла`);
    expect(blocks).toEqual([
      { kind: "specs", rows: [{ label, value: "из кварцевого стекла" }] },
    ]);
  });

  test("многословное название с двоеточием остаётся абзацем", () => {
    const blocks = parseDescription(
      "Общая рекомендация по хранению реагентов и расходных материалов: в сухом месте",
    );
    expect(blocks).toEqual([
      {
        kind: "paragraph",
        text: "Общая рекомендация по хранению реагентов и расходных материалов: в сухом месте",
      },
    ]);
  });

  test("заголовок с двоеточием перед списком становится подзаголовком", () => {
    const blocks = parseDescription("Выполняемые тесты:\n• Глюкоза\n• Билирубин");
    expect(blocks).toEqual([
      { kind: "heading", text: "Выполняемые тесты" },
      { kind: "list", items: ["Глюкоза", "Билирубин"] },
    ]);
  });

  test("заголовок с двоеточием без структуры следом остаётся абзацем", () => {
    const blocks = parseDescription("Память:\nПрибор поставляется в кейсе.");
    expect(blocks.some((b) => b.kind === "heading")).toBe(false);
  });

  test("заголовок открывает таблицу для одиночной длинной характеристики", () => {
    const long =
      "Особенности: Метод измерения прибора позволяет избежать влияние " +
      "липемичных и иктеричных образцов, а также оптически плотных веществ " +
      "в реагентах, четырёхканальная система измерения";
    expect(long.length).toBeGreaterThan(160);

    const blocks = parseDescription(`Технические характеристики:\n\n${long}`);
    expect(blocks).toEqual([
      { kind: "heading", text: "Технические характеристики" },
      {
        kind: "specs",
        rows: [
          { label: "Особенности", value: long.slice(long.indexOf(":") + 1).trim() },
        ],
      },
    ]);
  });

  test("пустые строки между характеристиками не дробят таблицу", () => {
    const rows = [
      ["Принцип измерения", "Абсорбция, одновременное считывание в 8-ми лунках"],
      ["Длины волн", "405, 450, 492, 630 нм + 3 свободные позиции"],
      ["Диапазон измерений", "0,0 - 3,5 опт. ед."],
      ["Диапазон линейности", "0,0 - 2,0 опт. ед."],
      ["Скорость считывания", "1 планшет за 5 секунд"],
      ["Память", "100 методик, 1000 данных о пациенте"],
      ["Контроль качества", "Построение кривых Леви-Дженингса"],
      ["Дисплей", "Сенсорный, 5,7\""],
      ["Ввод данных", "Через сенсорный экран, стилус или мышь"],
      ["Принтер", "Встроенный"],
      ["Размеры", "46х33х22 см"],
      ["Вес", "7,5 кг"],
      ["Гарантия", "12 месяцев"],
    ];
    const description = rows.map(([label, value]) => `${label}: ${value}`).join("\n\n");

    const blocks = parseDescription(description);
    expect(blocks).toEqual([
      {
        kind: "specs",
        rows: rows.map(([label, value]) => ({ label, value })),
      },
    ]);
  });

  test("пустые строки между пунктами списка не дробят его", () => {
    const blocks = parseDescription("• Диапазон волн 340-630\n\n• Источник света\n\n• Кювета");
    expect(blocks).toEqual([
      { kind: "list", items: ["Диапазон волн 340-630", "Источник света", "Кювета"] },
    ]);
  });

  test("заголовок между характеристиками разрывает таблицу на два блока", () => {
    const blocks = parseDescription(
      "Производительность: 60 тестов в час\n\nОбразцы\nТипы проб: сыворотка, плазма",
    );
    expect(blocks.map((b) => b.kind)).toEqual(["specs", "heading", "specs"]);
  });

  test("одиночная фраза средней длины с двоеточием остаётся абзацем", () => {
    // Раньше проходил лимит в 160 знаков и такая строка ошибочно становилась
    // таблицей из одной строки — новый лимит для одинокой строки строже (80).
    const value =
      "этот прибор предназначен для лабораторий среднего и крупного потока " +
      "проб в клинико-диагностических центрах";
    expect(value.length).toBeGreaterThan(80);
    expect(value.length).toBeLessThanOrEqual(160);

    const blocks = parseDescription(`Важно: ${value}`);
    expect(blocks).toEqual([{ kind: "paragraph", text: `Важно: ${value}` }]);
  });

  test("значение из нескольких предложений в одиночной строке остаётся абзацем", () => {
    const blocks = parseDescription(
      "Важно: Прибор компактен. Он подходит для малых лабораторий.",
    );
    expect(blocks).toEqual([
      {
        kind: "paragraph",
        text: "Важно: Прибор компактен. Он подходит для малых лабораторий.",
      },
    ]);
  });
});
